void main() {
  // Membuat variabel
  var angka1 = 10;
  var angka2 = 5;

  // Penjumlahan
  print("Penjumlahan $angka1 + $angka2 = ${angka1 + angka2}");

  // Pengurangan
  print("Pengurangan $angka1 - $angka2 = ${angka1 - angka2}");

  // Perkalian
  print("Perkalian $angka1 * $angka2 = ${angka1 * angka2}");

  // Pembagian
  print("Pembagian $angka1 / $angka2 = ${angka1 / angka2}");

  // Exit
  print("Exit");
}